//! The keymux plugin: [`super::core`] verbatim, the packed blob beside it, and the fixed interface
//! keymux's plugin loader calls (`alloc`, `fallback`, `joins`; see keymux's `docs/plugins/README.md`).
//!
//! keymux compiles a plugin from its `.rs` alone and caches the result by that file's content
//! hash, so the source names the blob's own hash: a new blob is a new source, and is recompiled.
//! The blob sits beside the source (`05-lyk-solver.bin`), which keymux's dictionary loader
//! ignores, and is read in at compile time by `include_bytes!`.

use std::hash::{Hash, Hasher};

/// The plugin's files: numbered after the dictionaries, so it only ever answers what they miss.
pub const SOURCE_FILE: &str = "05-lyk-solver.rs";
pub const BLOB_FILE: &str = "05-lyk-solver.bin";

const CORE: &str = include_str!("core.rs");

const INTERFACE: &str = r#"
// --- The interface keymux's plugin loader calls. See keymux's docs/plugins/README.md. ---

static BLOB: &[u8] = include_bytes!("05-lyk-solver.bin");

fn model() -> Option<&'static Model> {
    static MODEL: std::sync::OnceLock<Option<Model>> = std::sync::OnceLock::new();
    MODEL.get_or_init(|| Model::load(BLOB)).as_ref()
}

thread_local! {
    // keymux asks about the same run several times while it searches for the longest match
    static LAST: std::cell::RefCell<(String, Option<String>)> = const { std::cell::RefCell::new((String::new(), None)) };
}

#[no_mangle]
pub extern "C" fn alloc(len: i32) -> i32 {
    let mut buf: Vec<u8> = vec![0u8; len.max(0) as usize];
    let ptr = buf.as_mut_ptr();
    std::mem::forget(buf);
    ptr as i32
}

#[no_mangle]
pub extern "C" fn fallback(ptr: i32, len: i32) -> i64 {
    let bytes = unsafe { std::slice::from_raw_parts(ptr as *const u8, len.max(0) as usize) };
    let Ok(outline) = std::str::from_utf8(bytes) else { return -1 };
    let cached = LAST.with(|last| {
        let last = last.borrow();
        (last.0 == outline).then(|| last.1.clone())
    });
    let text = match cached {
        Some(text) => text,
        None => {
            let text = model().and_then(|m| m.answer(outline));
            LAST.with(|last| *last.borrow_mut() = (outline.to_owned(), text.clone()));
            text
        }
    };
    let Some(text) = text else { return -1 };
    let mut out = text.into_bytes();
    let out_len = out.len();
    let out_ptr = out.as_mut_ptr();
    std::mem::forget(out);
    (i64::from(out_ptr as i32) << 32) | i64::from(out_len as i32)
}

#[no_mangle]
pub extern "C" fn joins(bits: i64) -> i32 {
    i32::from(bits as u32 & JOIN != 0)
}
"#;

/// The plugin's source for a blob.
#[must_use]
pub fn source(blob: &[u8]) -> String {
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    blob.hash(&mut hasher);
    format!(
        "//! lyk's solver: a run of strokes that missed every dictionary, read as the word it most likely\n\
         //! meant. Generated by lyk-steno-theory (`build`); do not edit. It reads `{BLOB_FILE}` beside it\n\
         //! (blob {:016x}, {} bytes): regenerate both together.\n\
         #![allow(dead_code, clippy::all)]\n\n{CORE}\n{INTERFACE}",
        hasher.finish(),
        blob.len()
    )
}
